/// Look up a Tecno model by marketing name
pub fn find_tecno_model(name: &str) -> Option<TecnoModel> {
    let db = get_tecno_database();
    db.into_iter().find(|m| m.marketing_name.eq_ignore_ascii_case(name))
}

/// Search Tecno models matching a partial name, chipset, or series
pub fn search_tecno_models(query: &str) -> Vec<TecnoModel> {
    let db = get_tecno_database();
    let q = query.to_lowercase();
    db.into_iter().filter(|m| {
        m.marketing_name.to_lowercase().contains(&q) ||
        m.chipset.to_lowercase().contains(&q) ||
        m.series.to_lowercase().contains(&q) ||
        m.chipset_family.to_lowercase().contains(&q)
    }).collect()
}

/// Get all Tecno models in the database
pub fn list_all_tecno_models() -> Vec<TecnoModel> {
    get_tecno_database()
}

/// Get Tecno models filtered by series (Pop, Spark, Camon, Pova, Phantom)
pub fn get_tecno_by_series(series: &str) -> Vec<TecnoModel> {
    let db = get_tecno_database();
    let s = series.to_lowercase();
    db.into_iter().filter(|m| m.series.to_lowercase() == s).collect()
}

/// Get Tecno models filtered by chipset family
pub fn get_tecno_by_chipset_family(family: &str) -> Vec<TecnoModel> {
    let db = get_tecno_database();
    let f = family.to_lowercase();
    db.into_iter().filter(|m| m.chipset_family.to_lowercase() == f).collect()
}
