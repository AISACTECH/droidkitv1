/// Look up a Samsung model by its model code
pub fn find_model(model_code: &str) -> Option<SamsungModel> {
    let db = get_samsung_database();
    db.into_iter().find(|m| m.model_code.eq_ignore_ascii_case(model_code))
}

/// Search for models matching a partial name or code
pub fn search_models(query: &str) -> Vec<SamsungModel> {
    let db = get_samsung_database();
    let q = query.to_lowercase();
    db.into_iter().filter(|m| {
        m.model_code.to_lowercase().contains(&q) ||
        m.marketing_name.to_lowercase().contains(&q) ||
        m.chipset.to_lowercase().contains(&q)
    }).collect()
}

/// Get all unique models in the database
pub fn list_all_models() -> Vec<SamsungModel> {
    get_samsung_database()
}

